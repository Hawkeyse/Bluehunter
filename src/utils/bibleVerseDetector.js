const { extractReferences, fetchReferenceText } = require('./bibleReference');
const logger = require('./logger');

const LOOKUP_FAILURE_REPLY = "⚠️ I couldn't fetch that Bible verse right now. Please try again later.";

// A message that is plainly about time or everyday numbers is not a verse cue
// unless the bot was called by name or mention. This is the fix for the bot
// answering "I woke up at 7" with Scripture.
const BOT_CALLED_RE = /@\d{5,}|blue\s?hunter/i;
const TIME_TALK_RE = /\b(?:woke|wake|waking|slept|sleeping|clock|alarm|o'?clock)\b|\b\d{1,2}\s*(?:am|pm)\b/i;
const EXPLICIT_VERSE_RE = /\d{1,3}\s*:\s*\d{1,3}/;

/**
 * Detects Bible references typed in plain chat (e.g. "Psalm 121" or
 * "John 3:16"). A book and chapter without a verse means verse 1 of that
 * chapter. Text is always fetched from the Bible API, never generated by AI.
 */
async function maybeHandleBibleReference({ msg, translationCode }) {
  const body = msg.body || '';
  // Correlation guard: time talk without an explicit chapter:verse, and with
  // nobody calling the bot, is chat, not a Bible request.
  if (!BOT_CALLED_RE.test(body) && !EXPLICIT_VERSE_RE.test(body) && TIME_TALK_RE.test(body)) return false;

  const refs = extractReferences(body);
  if (!refs.length) return false;

  const results = [];
  for (const ref of refs) {
    try {
      const verse = await fetchReferenceText(ref, translationCode);
      if (verse) results.push(verse);
    } catch (err) {
      logger.warn('Bible reference lookup failed:', err.message); // skip this one, still show any others found
    }
  }
  if (!results.length) {
    await msg.reply(LOOKUP_FAILURE_REPLY);
    return true;
  }

  const text = results.map((v) => `*${v.reference}* (${v.translation})\n${v.text}`).join('\n\n');
  await msg.reply(text);
  return true;
}

module.exports = { maybeHandleBibleReference };
